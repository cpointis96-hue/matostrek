async function ensureBrand(brand) {
  const lookup = await nocoFetch(`${BRANDS_TABLE}?where=(slug,eq,${brand.slug})&limit=1`);
  const existing = lookup.list?.[0];
  if (existing) {
    const payload = pick(brand, ["name", "slug", "country", "website_url"]);
    await nocoFetch(`${BRANDS_TABLE}/${existing.Id}`, {
      method: "PATCH",
      body: JSON.stringify(payload),
    });
    return existing.Id;
  }

  const created = await nocoFetch(BRANDS_TABLE, {
    method: "POST",
    body: JSON.stringify(pick(brand, ["name", "slug", "country", "website_url"])),
  });
  return created.Id;
}

function writeRawData(record) {
  const dir = path.join(RAW_DIR, record.brand.slug);
  fs.mkdirSync(dir, { recursive: true });
  const target = path.join(dir, `${record.sleeping_bag.slug}.json`);
  fs.writeFileSync(target, `${JSON.stringify(record, null, 2)}\n`);
  return target;
}

async function upsertSleepingBag(record, brandId) {
  const payload = {
    ...pick(record.sleeping_bag, SLEEPING_BAG_FIELDS),
    brand_id: brandId,
  };

  const lookup = await nocoFetch(`${SLEEPING_BAGS_TABLE}?where=(slug,eq,${record.sleeping_bag.slug})&limit=1`);
  const existing = lookup.list?.[0];

  if (existing) {
    await nocoFetch(`${SLEEPING_BAGS_TABLE}/${existing.Id}`, {
      method: "PATCH",
      body: JSON.stringify(payload),
    });
    return { action: "updated", id: existing.Id };
  }

  const created = await nocoFetch(SLEEPING_BAGS_TABLE, {
    method: "POST",
    body: JSON.stringify(payload),
  });
  return { action: "created", id: created.Id };
}

async function main() {
  const results = [];
  for (const record of records) {
    const rawPath = writeRawData(record);
    const brandId = await ensureBrand(record.brand);
    const upsert = await upsertSleepingBag(record, brandId);
    results.push({
      slug: record.sleeping_bag.slug,
      brand: record.brand.slug,
      rawPath,
      brandId,
      sleepingBagId: upsert.id,
      action: upsert.action,
    });
  }

  console.log(JSON.stringify(results, null, 2));
}

